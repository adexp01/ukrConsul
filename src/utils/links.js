/*
 * Частина посилань у локалях стоїть заглушками `"#"`: сторінки або файлу під
 * них ще немає (біла книга, добірка подій, розширена мапа експорту).
 *
 * Клік по такому посиланню нічого не робить, зате кидає сторінку вгору — з
 * боку користувача це виглядає як зламана кнопка. Тому правило просте: якщо
 * цілі немає, кнопку не показуємо взагалі. Щойно в локалі зʼявиться справжня
 * адреса, кнопка повернеться сама, без правок у компонентах.
 */
export const hasDestination = (href) =>
  typeof href === "string" && href.trim() !== "" && href.trim() !== "#";

/** Чи веде посилання за межі застосунку */
export const isExternalUrl = (href) =>
  typeof href === "string" &&
  (/^https?:\/\//i.test(href) ||
    href.startsWith("mailto:") ||
    href.startsWith("tel:"));
